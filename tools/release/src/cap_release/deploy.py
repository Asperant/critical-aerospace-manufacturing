class SystemHost:
    """The shared Integration host: git, GitHub, Docker and infra/compose/stack.sh."""

    def __init__(
        self, repo_root: Path, state_dir: Path | None = None, profile: str = "full"
    ) -> None:
        self.root = repo_root
        self.profile = profile
        self.state = state_dir or Path(
            os.environ.get(
                "CAP_RELEASE_STATE_DIR", Path.home() / ".local/state/cap-release"
            )
        )

    def _run(self, argv: list[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            argv, cwd=self.root, capture_output=True, text=True, check=False, **kwargs
        )

    def now(self) -> dt.datetime:
        return dt.datetime.now(dt.UTC)

    def checked_out_commit(self) -> str:
        return self._run(["git", "rev-parse", "HEAD"]).stdout.strip()

    def tree_changes(self) -> list[str]:
        return [
            line
            for line in self._run(["git", "status", "--porcelain"]).stdout.splitlines()
            if line.strip()
        ]

    def commit_on_main(self, commit: str) -> bool:
        self._run(["git", "fetch", "--quiet", "origin", "main"])
        return (
            self._run(
                ["git", "merge-base", "--is-ancestor", commit, "origin/main"]
            ).returncode
            == 0
        )

    def ci_gate_conclusion(self, commit: str) -> str | None:
        done = self._run(
            [
                "gh",
                "api",
                f"repos/{REPOSITORY}/commits/{commit}/check-runs",
                "--jq",
                '[.check_runs[]|select(.name=="ci-gate")|.conclusion]|first // empty',
            ]
        )
        if done.returncode != 0:
            raise DeployError(
                (done.stderr or done.stdout).strip()[-300:]
                or f"gh exited {done.returncode}"
            )
        return done.stdout.strip() or None

    def digest_in_registry(self, reference: str) -> bool:
        return (
            self._run(
                ["docker", "buildx", "imagetools", "inspect", reference]
            ).returncode
            == 0
        )

    def rollout(self, override: str) -> None:
        self.state.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(
            "w", suffix=".yaml", dir=self.state, delete=False
        ) as handle:
            handle.write(override)
            path = handle.name
        done = self._run(
            ["infra/compose/stack.sh", "up", self.profile],
            env={**os.environ, "CAP_COMPOSE_OVERRIDE": path},
        )
        if done.returncode != 0:
            raise DeployError((done.stderr or done.stdout)[-400:].strip())

    def unhealthy(self) -> list[str]:
        done = self._run(
            [
                "docker",
                "ps",
                "--all",
                "--filter",
                "label=com.docker.compose.project=cap-platform",
                "--format",
                '{{.Label "com.docker.compose.service"}}\t{{.State}}\t{{.Status}}',
            ]
        )
        bad: list[str] = []
        for line in done.stdout.splitlines():
            service, state, status = line.split("\t", 2)
            if state == "exited" and "Exited (0)" in status:
                continue  # a completed one-shot setup job
            if "(healthy)" not in status:
                bad.append(f"{service}={state}")
        return bad

    def smoke(self) -> bool:
        return self._run(["infra/compose/stack.sh", "smoke"]).returncode == 0

    def migrate(self, target: str) -> None:
        raise DeployError(f"no migration runner is wired for {target} (WP-CICD-003)")

    def last_succeeded(self) -> tuple[dict[str, Any], dict[str, Any]] | None:
        records = (
            sorted((self.state / "records").glob("*.json"))
            if (self.state / "records").is_dir()
            else []
        )
        for path in reversed(records):
            record = cast("dict[str, Any]", json.loads(path.read_text("utf-8")))
            if record.get("result") == "SUCCEEDED":
                manifest_path = self.state / "releases" / f"{record['release_id']}.json"
                if manifest_path.is_file():
                    return record, cast(
                        "dict[str, Any]", json.loads(manifest_path.read_text("utf-8"))
                    )
        return None

    def save(self, manifest: Mapping[str, Any], record: Mapping[str, Any]) -> None:
        for sub in ("records", "releases"):
            (self.state / sub).mkdir(parents=True, exist_ok=True)
        (self.state / "releases" / f"{manifest['release_id']}.json").write_bytes(
            canonical_bytes(manifest)
        )
        (self.state / "records" / f"{record['record_id']}.json").write_text(
            json.dumps(record, indent=2, sort_keys=True) + "\n", "utf-8"
        )
