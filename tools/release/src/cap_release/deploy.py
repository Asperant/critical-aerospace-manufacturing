"""Digest-pinned deployment of a ReleaseManifest, with a DeploymentRecord.

02 (CD, normative statements): a deployment originates from a CI-built immutable
artifact resolved from the registry, never built from source on the target; CD does
not trust tags, it verifies the exact digest; SUCCEEDED needs Preflight, Migration,
Rollout, Health and Smoke to have passed. NFR-DEP-003: zero manual source patches on
the host. Everything that touches the system goes through `Host`, so the decisions
here are tested with a fake host and exercised for real by `SystemHost`.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import subprocess
import tempfile
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol, cast

from cap_release.manifest import canonical_bytes, fingerprint, validate_manifest
from cap_release.record import (
    STAGES,
    new_record_id,
    not_run,
    stage,
    timestamp,
    validate_record,
)
from cap_release.registry import ImageRegistry

REPOSITORY = "Asperant/critical-aerospace-manufacturing"


class DeployError(Exception):
    """A rollout, health or smoke step failed."""


class Host(Protocol):
    def now(self) -> dt.datetime: ...
    def checked_out_commit(self) -> str: ...
    def tree_changes(self) -> list[str]: ...
    def commit_on_main(self, commit: str) -> bool: ...
    def ci_gate_conclusion(self, commit: str) -> str | None: ...
    def digest_in_registry(self, reference: str) -> bool: ...
    def rollout(self, override: str) -> None: ...
    def unhealthy(self) -> list[str]: ...
    def smoke(self) -> bool: ...
    def migrate(self, target: str) -> None: ...
    def last_succeeded(self) -> tuple[dict[str, Any], dict[str, Any]] | None: ...
    def save(self, manifest: Mapping[str, Any], record: Mapping[str, Any]) -> None: ...


def render_override(registry: ImageRegistry, manifest: Mapping[str, Any]) -> str:
    """A Compose override that pins every released service to its digest and never builds."""
    pinned = {
        str(item["name"]): str(item["reference"])
        for item in cast("list[dict[str, Any]]", manifest["service_images"])
    }
    lines = [
        "# Generated by cap_release deploy: digest-pinned, no build on the target.",
        "services:",
    ]
    for image in registry.images:
        reference = pinned.get(image.name)
        if reference is None:
            raise DeployError(f"the manifest does not contain image {image.name}")
        for service in image.compose_services:
            lines += [
                f"  {service}:",
                f"    image: {reference}",
                "    build: !reset null",
            ]
    return "\n".join(lines) + "\n"


@dataclass
class Outcome:
    record: dict[str, Any]
    exit_code: int


def _database_target(manifest: Mapping[str, Any]) -> str | None:
    target = manifest.get("database_schema_target")
    if (
        isinstance(target, dict)
        and cast("dict[str, Any]", target).get("state") == "BOUND"
    ):
        return str(cast("dict[str, Any]", target)["identity"])
    return None


def deploy(
    manifest: dict[str, Any],
    registry: ImageRegistry,
    host: Host,
    *,
    environment_id: str = "integration",
    environment_class: str = "INTEGRATION",
) -> Outcome:
    """Run the five stages and return the record; the record is also saved through `host`."""
    started = host.now()
    commit = str(cast("dict[str, Any]", manifest.get("source", {})).get("commit", ""))
    checked_out = host.checked_out_commit()
    patches = host.tree_changes()
    stages: list[dict[str, Any]] = []
    chain: dict[str, Any] = {
        "main_derived": False,
        "ci_gate": "unknown",
        "digests_in_registry": False,
        "tags_trusted": False,
    }

    # --- preflight -------------------------------------------------------------
    p_start = host.now()
    failures = [f"manifest: {problem}" for problem in validate_manifest(manifest)]
    if checked_out != commit:
        failures.append(
            f"the host checkout {checked_out[:12]} is not the release commit {commit[:12]}"
        )
    if patches:
        failures.append(
            f"{len(patches)} manual change(s) in the host source tree (NFR-DEP-003): {patches[:3]}"
        )
    chain["main_derived"] = host.commit_on_main(commit)
    if not chain["main_derived"]:
        failures.append("the release commit is not on main")
    try:
        chain["ci_gate"] = host.ci_gate_conclusion(commit) or "missing"
    except DeployError as exc:
        # An unreadable check is not an absent one: say which, so the operator can fix it.
        chain["ci_gate"] = "unreadable"
        failures.append(f"ci-gate could not be read from GitHub: {exc}")
    else:
        if chain["ci_gate"] != "success":
            failures.append(
                f"ci-gate at the release commit is {chain['ci_gate']}, not success"
            )
    references = [
        str(i["reference"])
        for i in cast("list[dict[str, Any]]", manifest.get("service_images", []))
    ]
    absent = [ref for ref in references if not host.digest_in_registry(ref)]
    chain["digests_in_registry"] = bool(references) and not absent
    if absent:
        failures.append(f"digest not found in the registry: {absent}")
    stages.append(
        stage(
            "preflight",
            "FAILED" if failures else "PASSED",
            "; ".join(failures)
            or "main-derived, ci-gate green, digests present, host source clean",
            p_start,
            host.now(),
        )
    )

    previous = host.last_succeeded() if not failures else None
    result = "FAILED"
    rollback: dict[str, Any] | None = None

    def stop(reason: str) -> None:
        for name in STAGES[len(stages) :]:
            stages.append(not_run(name, reason))

    if failures:
        stop("preflight failed; nothing was rolled out")
    else:
        # --- migrate ------------------------------------------------------------
        m_start = host.now()
        target = _database_target(manifest)
        if target is None:
            stages.append(
                stage(
                    "migrate",
                    "SKIPPED",
                    "the release binds no database schema target",
                    m_start,
                    host.now(),
                )
            )
        else:
            try:
                host.migrate(target)
                stages.append(
                    stage(
                        "migrate",
                        "PASSED",
                        f"database at {target}",
                        m_start,
                        host.now(),
                    )
                )
            except DeployError as exc:
                stages.append(stage("migrate", "FAILED", str(exc), m_start, host.now()))
        if stages[-1]["result"] == "FAILED":
            stop("migration failed; nothing was rolled out")
        else:
            # --- rollout ---------------------------------------------------------
            r_start = host.now()
            try:
                host.rollout(render_override(registry, manifest))
                stages.append(
                    stage(
                        "rollout",
                        "PASSED",
                        "released services started from their digests",
                        r_start,
                        host.now(),
                    )
                )
            except DeployError as exc:
                stages.append(stage("rollout", "FAILED", str(exc), r_start, host.now()))
            if stages[-1]["result"] == "PASSED":
                h_start = host.now()
                bad = host.unhealthy()
                stages.append(
                    stage(
                        "health",
                        "FAILED" if bad else "PASSED",
                        f"not healthy: {bad}" if bad else "every service healthy",
                        h_start,
                        host.now(),
                    )
                )
            if stages[-1]["result"] == "PASSED":
                s_start = host.now()
                ok = host.smoke()
                stages.append(
                    stage(
                        "smoke",
                        "PASSED" if ok else "FAILED",
                        "REAL smoke checks passed"
                        if ok
                        else "REAL smoke checks failed",
                        s_start,
                        host.now(),
                    )
                )
            stop("an earlier stage did not pass")
            result = (
                "SUCCEEDED"
                if all(s["result"] in {"PASSED", "SKIPPED"} for s in stages)
                else "FAILED"
            )
            if result == "FAILED" and previous is not None:
                old_record, old_manifest = previous
                try:
                    host.rollout(render_override(registry, old_manifest))
                    rollback = {
                        "to_release_id": str(old_record["release_id"]),
                        "result": "SUCCEEDED",
                    }
                    result = "ROLLED_BACK"
                except DeployError:
                    rollback = {
                        "to_release_id": str(old_record["release_id"]),
                        "result": "FAILED",
                    }

    finished = host.now()
    record: dict[str, Any] = {
        "schema": "cap.deployment-record/v1",
        "record_id": new_record_id(started),
        "release_id": manifest.get("release_id"),
        "manifest_sha256": fingerprint(manifest),
        "environment": {"id": environment_id, "class": environment_class},
        "host_source": {
            "checked_out_commit": checked_out,
            "release_commit": commit,
            "manual_patches": len(patches),
        },
        "supply_chain_verification": chain,
        "stages": stages,
        "result": result,
        "previous_release_id": str(previous[0]["release_id"]) if previous else None,
        "rollback": rollback,
        "started_at": timestamp(started),
        "finished_at": timestamp(finished),
    }
    problems = validate_record(record, manifest)
    if problems:
        raise DeployError(f"the deployment record would be inconsistent: {problems}")
    host.save(manifest, record)
    return Outcome(record=record, exit_code=0 if result == "SUCCEEDED" else 1)


